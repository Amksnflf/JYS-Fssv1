#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Insert new i18n keys into 13 locale files after known anchor lines."""
import os
import re

LOCALES_DIR = os.path.join(os.path.dirname(__file__), '..', 'src', 'i18n', 'locales')

# Per-language translations. Structure:
# lang -> { block_name -> {key: value} }
NAV_KEYS = ['quotes', 'spot', 'contract', 'marketData', 'moreNews', 'travel', 'nft',
            'quotesDesc', 'spotDesc', 'contractDesc', 'marketDataDesc', 'moreNewsDesc',
            'travelDesc', 'nftDesc', 'deposit', 'withdraw', 'transfer', 'creditSecurity',
            'securityCenter', 'primaryKyc', 'shareFriends', 'logout', 'verified', 'unverified']
HOME_KEYS = ['heroStart', 'onlineService', 'announcement', 'proTitle', 'proSub', 'aiSlogan',
             'followTitle', 'followSub', 'strategist', 'follow', 'returnRate', 'winRate',
             'followers', 'goInvest', 'daysUnit']
ASSET_KEYS = ['statusWaiting', 'statusDepositFailed', 'statusAbnormal', 'statusExpired', 'statusArrived']
DEPOSIT_KEYS = ['credited', 'addressGenerated', 'generateFailed', 'manual', 'auto',
                'autoAmountPlaceholder', 'regenerateAddress', 'generateAddress', 'sendToAddress',
                'orderNo', 'status', 'expireAt']
NEWS_KEYS = ['loadFailed', 'detailTitle', 'noContent']

# D[lang] = flat dict of key -> translated value
D = {}


def esc(v):
    return v.replace("'", "\\'")


def block_lines(d, keys, indent='    '):
    return ''.join("%s%s: '%s',\n" % (indent, k, esc(d[k])) for k in keys)


def patch(lang):
    d = D[lang]
    path = os.path.join(LOCALES_DIR, lang + '.ts')
    with open(path, encoding='utf-8') as f:
        src = f.read()

    # common.all — after `language: '...',`
    src = re.sub(r"(\n    language: '[^']*',)",
                 lambda m: m.group(1) + "\n    all: '%s'," % esc(d['all']), src, count=1)

    # nav block — after `assets: '...',` (end of nav)
    src = re.sub(r"(\n    assets: '[^']*',)",
                 lambda m: m.group(1) + '\n' + block_lines(d, NAV_KEYS).rstrip('\n'),
                 src, count=1)

    # home block — after `businessContact: '...',`
    src = re.sub(r"(\n    businessContact: '[^']*',)",
                 lambda m: m.group(1) + '\n' + block_lines(d, HOME_KEYS).rstrip('\n'),
                 src, count=1)

    # trade.symbol — after `selectSymbol: '...',`
    src = re.sub(r"(\n    selectSymbol: '[^']*',)",
                 lambda m: m.group(1) + "\n    symbol: '%s'," % esc(d['symbol']),
                 src, count=1)

    # market.dynamicTitle — after `commentCount: '...',`
    src = re.sub(r"(\n    commentCount: '[^']*',)",
                 lambda m: m.group(1) + "\n    dynamicTitle: '%s'," % esc(d['dynamicTitle']),
                 src, count=1)

    # asset status keys — after `switchAccounts: '...',`
    src = re.sub(r"(\n    switchAccounts: '[^']*',)",
                 lambda m: m.group(1) + '\n' + block_lines(d, ASSET_KEYS).rstrip('\n'),
                 src, count=1)

    # deposit + news blocks — before `  security: {`
    dep = "  deposit: {\n" + block_lines(d, DEPOSIT_KEYS) + "  },\n"
    news = "  news: {\n" + block_lines(d, NEWS_KEYS) + "  },\n"
    src = re.sub(r"(\n  security: \{)",
                 lambda m: '\n' + dep + news + m.group(1).lstrip('\n'),
                 src, count=1)

    with open(path, 'w', encoding='utf-8') as f:
        f.write(src)
    print('patched', lang)


